#!/usr/bin/env node
/**
 * DSH Copilot pet — bundle builder.
 *
 * 把 plugin/src/client.body.js（手写逻辑体）与 plugin/src/assets.gen.json（素材内联包）
 * 合成为客户端模块系统要求的经典脚本：
 *
 *   window.__ModuleLoader__.load({
 *     id: "<包名>",
 *     factory: (require) => { var module = {exports:{}}; var exports = module.exports; ... }
 *   })
 *
 * 为什么手写而不是用 tsdown：仓库内的 clientBundle 预设没有发布，外部插件要复刻它就得
 * 引入整套构建依赖；这里刻意保持"零依赖 + 可审计的生成物"，产物本身就是可以直接读的
 * 普通 JS（不压缩、不混淆），便于安装前人工审阅。
 *
 * 确定性：同一份输入必然产出同一份字节（生成物里不写时间戳），供 --check 做漂移比对。
 *
 * 用法：
 *   node tools/build_bundle.mjs           # 生成 plugin/lib/client.js
 *   node tools/build_bundle.mjs --check   # 与磁盘上的产物比对，drift 则退出码 1
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const PACKAGE_JSON = join(ROOT, 'plugin', 'package.json')
const BODY_FILE = join(ROOT, 'plugin', 'src', 'client.body.js')
const ASSETS_FILE = join(ROOT, 'plugin', 'src', 'assets.gen.json')
const OUT_FILE = join(ROOT, 'plugin', 'lib', 'client.js')

const BANNER = `/* DSH Copilot pet — generated by tools/build_bundle.mjs. Do not edit by hand.
 * Sources: plugin/src/client.body.js + plugin/src/assets.gen.json
 * Readable on purpose: no minification, no obfuscation, no network code. */`

/**
 * @param {string} packageName
 * @param {string} body
 * @param {string} assetsJson
 * @returns {string}
 */
function buildBundle(packageName, body, assetsJson) {
  const indented = body.replace(/^(?=.)/gm, '\t\t')
  return `${BANNER}
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(packageName)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
\t\tconst React = require("react");
\t\tconst PET_ASSETS = ${assetsJson};
${indented}
\t\treturn module.exports;
\t}
});
`
}

/**
 * @returns {{ packageName: string, output: string }}
 */
function generate() {
  const pkg = JSON.parse(readFileSync(PACKAGE_JSON, 'utf8'))
  if (typeof pkg.name !== 'string' || pkg.name === '') throw new Error('plugin/package.json has no name')
  const body = readFileSync(BODY_FILE, 'utf8')
  if (!/exports\.apply/.test(body)) throw new Error('client.body.js never assigns exports.apply')
  if (/\bimport\s|\bexport\s+(?:const|function|class|default)\b/.test(body)) {
    throw new Error('client.body.js must be a plain script body (no import/export statements)')
  }
  const assetsRaw = readFileSync(ASSETS_FILE, 'utf8')
  const assets = JSON.parse(assetsRaw) // 校验可解析；写入时使用同一份文本（保持确定性）
  if (assets?.sprite?.uri === undefined) throw new Error('assets.gen.json is missing sprite.uri')
  const output = buildBundle(pkg.name, body, assetsRaw.trim())
  return { packageName: pkg.name, output }
}

function main() {
  const check = process.argv.includes('--check')
  const { packageName, output } = generate()
  const digest = createHash('sha256').update(output).digest('hex')
  if (check) {
    const existing = existsSync(OUT_FILE) ? readFileSync(OUT_FILE, 'utf8') : null
    if (existing !== output) {
      console.error(`bundle drift: ${OUT_FILE} is not what the current sources generate`)
      process.exitCode = 1
      return
    }
    console.log(`bundle: no drift (${packageName}, sha256 ${digest.slice(0, 16)}…)`)
    return
  }
  mkdirSync(dirname(OUT_FILE), { recursive: true })
  writeFileSync(OUT_FILE, output)
  console.log(`wrote ${OUT_FILE}`)
  console.log(`  package : ${packageName}`)
  console.log(`  bytes   : ${Buffer.byteLength(output)}`)
  console.log(`  sha256  : ${digest}`)
}

main()
